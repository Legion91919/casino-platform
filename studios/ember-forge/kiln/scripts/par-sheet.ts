// Writes a game's docs/par-sheet.md: exact RTP when the game has no features, seeded simulation
// statistics always. Usage (from a game folder's script): writeParSheet({...}).
import { writeFileSync } from "node:fs";
import { exactLineRtp, simulateRtp } from "../src/math/rtp.ts";
import { mathModelSha256 } from "../src/math/hash.ts";
import type { GameMath } from "../src/math/types.ts";

export function writeParSheet(o: { file: string | URL; title: string; version: string; math: GameMath; featureRules: string; declaredBps?: number; spins: number; notes?: string }) {
  const c = o.math.config;
  const exact = o.featureRules === "none" ? exactLineRtp(c) : null;
  const sim = simulateRtp(o.math, o.spins, 1);
  const pct = (x: number) => `${(x * 100).toFixed(2)}%`;
  const counts = c.strips.map((s) => Object.fromEntries(c.symbols.map((sym) => [sym, s.filter((x) => x === sym).length])));
  const declared = exact ? exact.rtpBps : o.declaredBps!;
  const z = (sim.rtp - declared / 10_000) / sim.standardError;
  const md = `# ${o.title} ${o.version}: PAR sheet

Generated by \`npm run par\` (Kiln). Math model \`${mathModelSha256(c, o.featureRules)}\`, feature rules \`${o.featureRules}\`.

## Return to player
${exact
    ? `**Exact: ${(exact.rtp * 100).toFixed(4)}%** over all ${exact.cycle.toLocaleString("en")} equally likely stop combinations (declared ${exact.rtpBps} bps). Line pays ${pct(exact.linePayPerCycle / exact.cycle)}, scatter ${pct(exact.scatterPayPerCycle / exact.cycle)}. Method proved against brute force in Kiln's tests.`
    : `**Declared ${(declared / 100).toFixed(2)}%** (${declared} bps), established by simulation because features carry wilds from one spin to the next. The simulation below gives ${pct(sim.rtp)} with a standard error of ${(sim.standardError * 100).toFixed(3)} points (z = ${z.toFixed(2)}); the game's tests re-check it with a different seed on every run.`}
${o.notes ? `\n${o.notes}\n` : ""}
## Play statistics (seeded simulation, ${sim.spins.toLocaleString("en")} rounds, seed 1)

| | |
|---|---|
| Simulated RTP | ${pct(sim.rtp)} (standard error ${(sim.standardError * 100).toFixed(3)} points) |
| Hit frequency (any win) | ${pct(sim.hitRate)} (1 in ${(1 / sim.hitRate).toFixed(2)}) |
| Rounds with a feature | ${pct(sim.featureRate)}${sim.featureRate ? ` (1 in ${(1 / sim.featureRate).toFixed(1)})` : ""} |
| Average spins per round | ${sim.avgSteps.toFixed(3)} |
| Standard deviation per round | ${sim.sd.toFixed(2)} x stake |
| Largest win seen | ${sim.maxWin.toFixed(1)} x stake |

| Win, times stake | Share of rounds |
|---|---|
${["0", "up to 1", "1 to 5", "5 to 20", "20 to 100", "over 100"].map((l, i) => `| ${l} | ${pct(sim.buckets[i]! / sim.spins)} |`).join("\n")}

## Reel strips (counts per reel)

| Symbol | ${c.strips.map((_, i) => `Reel ${i + 1}`).join(" | ")} |
|---|${c.strips.map(() => "---").join("|")}|
${c.symbols.filter((s) => counts.some((k) => k[s])).map((s) => `| ${s} | ${counts.map((k) => k[s]).join(" | ")} |`).join("\n")}

Paytable (times line bet for 3/4/5): ${Object.entries(c.paytable).map(([s, p]) => `${s} ${p.join("/")}`).join(", ")}.${c.scatterPays ? ` Scatter (times total stake, 3/4/5 anywhere): ${c.scatterPays.join("/")}.` : ""}
`;
  writeFileSync(o.file, md);
  return { sim, exact };
}
