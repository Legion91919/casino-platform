// Reel strips for Land of Rock Paper Scissors from symbol counts; prints src/strips.ts.
// Usage: node scripts/build-strips.ts > src/strips.ts
// Rock, paper and scissors are one per reel: rare enough that a feature lands about once in 13 rounds.
import { buildStrips } from "@ember-forge/kiln/math";

export const STRIP_LENGTH = 30;
export const STRIP_COUNTS: Record<string, number>[] = [
  { crane: 1, rock: 1, paper: 1, scissors: 1, sun: 4, moon: 6, star: 8, cloud: 8 },
  { crane: 2, rock: 1, paper: 1, scissors: 1, sun: 4, moon: 5, star: 8, cloud: 8 },
  { crane: 2, rock: 1, paper: 1, scissors: 1, sun: 4, moon: 5, star: 8, cloud: 8 },
  { crane: 1, rock: 1, paper: 1, scissors: 1, sun: 4, moon: 5, star: 8, cloud: 9 },
  { crane: 1, rock: 1, paper: 1, scissors: 1, sun: 4, moon: 6, star: 8, cloud: 8 },
];

if (import.meta.url === `file://${process.argv[1]}`) {
  const strips = buildStrips(STRIP_COUNTS, STRIP_LENGTH, 7);
  console.log("// Generated by scripts/build-strips.ts from STRIP_COUNTS. Never edit by hand.");
  console.log("export const STRIPS: readonly (readonly string[])[] = [");
  for (const s of strips) console.log(`  [${s.map((x) => JSON.stringify(x)).join(",")}],`);
  console.log("];");
}
